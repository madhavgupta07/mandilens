import { describe, it, expect, beforeAll, afterAll, beforeEach } from "vitest";
import mongoose from "mongoose";
import { connectToDatabase, disconnectFromDatabase } from "@/lib/db/connect";
import { ingestRecords, type NormalizedInput } from "@/lib/services/ingestion";
import { runDeterministicAssistant } from "@/lib/ai/deterministic";
import { DETERMINISTIC_BANNER } from "@/lib/ai/prompts";
import { buildDedupeKey, slugify } from "@/lib/utils/slug";
import { clearDatabase } from "../helpers/db";

const NOW = new Date("2026-03-22T12:00:00.000Z");
    const seededDate = "2026-03-19T00:00:00.000Z";

function priceRecord(marketName: string, district: string, modal: number, date: string): NormalizedInput {
  const priceDate = new Date(date);
  return {
    sourceKey: "admin_csv",
    state: "Bihar",
    district,
    marketName,
    commodityName: "Maize",
    unit: "quintal",
    currency: "INR",
    minPrice: modal - 100,
    maxPrice: modal + 100,
    modalPrice: modal,
    priceDate,
    recordType: "reported_market_price",
    dedupeKey: buildDedupeKey(["admin_csv", slugify(marketName), "maize", "", "", date.slice(0, 10)]),
    validationStatus: "valid",
    validationNotes: [],
  };
}

beforeAll(async () => {
  await connectToDatabase();
});

afterAll(async () => {
  await disconnectFromDatabase();
  await mongoose.connection.close().catch(() => undefined);
});

beforeEach(async () => {
  await clearDatabase();
  await ingestRecords([
    priceRecord("Samastipur Mandi", "Samastipur", 1900, "2026-03-19T00:00:00.000Z"),
    priceRecord("Bhagalpur Mandi", "Bhagalpur", 2050, "2026-03-19T00:00:00.000Z"),
    priceRecord("Muzaffarpur Mandi", "Muzaffarpur", 2000, "2026-03-19T00:00:00.000Z"),
  ]);
});

describe("deterministic assistant grounding", () => {
  it("answers a comparison using real tools and marks the result grounded", async () => {
    const result = await runDeterministicAssistant({
      question: "compare 50 quintals of maize with transport cost",
      user: null,
      now: NOW,
    });

    expect(result.mode).toBe("deterministic");
    expect(result.grounded).toBe(true);
    expect(result.toolTrace.length).toBeGreaterThanOrEqual(1);
    expect(result.toolTrace[0].name).toBe("compareMarkets");
    expect(result.toolTrace[0].ok).toBe(true);
    expect(result.answer).toContain(DETERMINISTIC_BANNER);
    expect(result.notes.join(" ")).toMatch(/opportunity engine/i);
  });

  it("never claims AI authorship in deterministic mode", async () => {
    const result = await runDeterministicAssistant({
      question: "latest maize prices in Samastipur",
      user: null,
      now: NOW,
    });
    expect(result.answer).toMatch(/not generated by an AI model/i);
  });

  it("asks for a commodity instead of inventing one", async () => {
    const result = await runDeterministicAssistant({
      question: "compare 50 quintals of dragonfruit",
      user: null,
      now: NOW,
    });
    expect(result.grounded).toBe(false);
    expect(result.toolTrace).toHaveLength(0);
    expect(result.answer).toMatch(/which commodity/i);
    expect(result.answer).not.toMatch(/dragonfruit.*net proceeds/i);
  });

  it("requests a quantity before running a comparison", async () => {
    const result = await runDeterministicAssistant({
      question: "which market is best for maize",
      user: null,
      now: NOW,
    });
    expect(result.missingData).toBe(true);
    expect(result.answer).toMatch(/need the quantity/i);
  });

  it("handles a help request without touching the database tools", async () => {
    const result = await runDeterministicAssistant({
      question: "what can you do",
      user: null,
      now: NOW,
    });
    expect(result.grounded).toBe(false);
    expect(result.toolTrace).toHaveLength(0);
    expect(result.answer).toContain(DETERMINISTIC_BANNER);
  });

  it("reports the freshness of stored data honestly", async () => {
    const result = await runDeterministicAssistant({
      question: "how fresh is the maize data",
      user: null,
      now: NOW,
    });
    expect(result.toolTrace[0].name).toBe("getDataFreshness");
    expect(result.grounded).toBe(true);
    expect(result.answer).toMatch(/fresh|recent|aging|stale/i);
  });

  it("always discloses its provenance in the tool trace", async () => {
    const result = await runDeterministicAssistant({
      question: "latest maize prices",
      user: null,
      now: NOW,
    });
    for (const entry of result.toolTrace) {
      expect(typeof entry.name).toBe("string");
      expect(typeof entry.summary).toBe("string");
      expect(entry.summary.length).toBeGreaterThan(0);
    }
  });
});
